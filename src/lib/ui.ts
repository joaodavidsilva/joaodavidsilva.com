const UI: Partial<Record<Language, Ui>> = { en, pt };

/** The site's words in `language`, English where it has none of its own. */
export const uiOf = (language: Language): Ui => UI[language] ?? en;

/** The site's words for the page at `url`, by its language prefix. */
export const uiAt = (url: URL): Ui => uiOf(languageOfPath(url.pathname));
